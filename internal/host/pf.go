type VMProxyStatus struct {
	ConfigEnabled        bool     `json:"config_enabled"`
	PeacePFAnchorExists   bool     `json:"peace_pf_anchor_exists"`
	LegacyPFAnchorExists bool     `json:"legacy_pf_anchor_exists"`
	LegacyDaemonInstalled bool    `json:"legacy_daemon_installed"`
	CoworkBridgeActive   bool     `json:"cowork_bridge_active"`
	CoworkBridgeIP       string   `json:"cowork_bridge_ip,omitempty"`
	RenderedAnchorPath   string   `json:"rendered_anchor_path"`
	InstallScriptPath    string   `json:"install_script_path"`
	UninstallScriptPath  string   `json:"uninstall_script_path"`
	SyntaxValid          bool     `json:"syntax_valid"`
	SyntaxDetail         string   `json:"syntax_detail,omitempty"`
	ActivePFNote         string   `json:"active_pf_note"`
	Subnets              []string `json:"subnets"`
}

func RenderPFAnchor(cfg *config.Config) string {
	v4List := strings.Join(policy.AnthropicV4CIDRs, " ")
	v6List := strings.Join(policy.AnthropicV6CIDRs, " ")

	var sb strings.Builder
	sb.WriteString("# PeaceClaude macOS pf killswitch & Cowork VM anti-leak anchor\n")
	sb.WriteString("# Validate syntax: /sbin/pfctl -n -a peaceclaude -f <this-file>\n")
	sb.WriteString(fmt.Sprintf("table <peace_anthropic_v4> persist { %s }\n", v4List))

	// Allow direct outbound ONLY to the configured upstream static proxy host:port (when direct mode).
	if cfg != nil && cfg.Upstream.Address != "" {
		if h, p, err := net.SplitHostPort(cfg.Upstream.Address); err == nil {
			if ip := net.ParseIP(h); ip != nil && !ip.IsLoopback() {
				sb.WriteString(fmt.Sprintf("table <peace_upstream_proxy> persist { %s }\n", h))
				sb.WriteString(fmt.Sprintf("pass out quick proto tcp from any to <peace_upstream_proxy> port %s\n", p))
			}
		}
	}

	// If Cowork VM proxy protection is enabled, allow VM subnet -> host peaceclaude proxy ports,
	// and block VM subnet from sending direct traffic to Anthropic CIDRs or UDP/443 QUIC.
	if cfg != nil && cfg.Listen.VMProxyEnabled && len(cfg.Listen.VMProxySubnets) > 0 {
		subnets := strings.Join(cfg.Listen.VMProxySubnets, " ")
		sb.WriteString(fmt.Sprintf("table <peace_cowork_vm> persist { %s }\n", subnets))
		sb.WriteString(fmt.Sprintf("pass in quick proto tcp from <peace_cowork_vm> to any port { %d %d }\n",
			cfg.Listen.HTTPPort, cfg.Listen.SOCKS5Port))
		sb.WriteString("block drop quick proto udp from <peace_cowork_vm> to any port 443\n")
		sb.WriteString("block drop quick proto tcp from <peace_cowork_vm> to <peace_anthropic_v4>\n")
	}

	// Host-wide fail-closed killswitch: drop any direct TCP/UDP/IPv6 to Anthropic CIDRs.
	sb.WriteString("block drop out quick proto tcp from any to <peace_anthropic_v4>\n")
	sb.WriteString("block drop out quick proto udp from any to <peace_anthropic_v4>\n")
	sb.WriteString(fmt.Sprintf("block drop out quick inet6 from any to %s\n", v6List))
	return sb.String()
}

func RenderPFScripts(anchorSrc string) (installSh, uninstallSh string) {
	installSh = fmt.Sprintf(`#!/usr/bin/env bash
# Generated by peaceclaude vm-proxy — installs macOS pf anchor safely without flushing Apple/Feilian rules.
set -euo pipefail
if [[ "$(id -u)" -ne 0 ]]; then
  echo "Please run with sudo: sudo bash %s" >&2
  exit 1
fi
ANCHOR_NAME="peaceclaude"
ANCHOR_SRC=%q
ANCHOR_DST="/etc/pf.anchors/peaceclaude"
PF_CONF="/etc/pf.conf"
MARK_BEGIN="# BEGIN peaceclaude"
MARK_END="# END peaceclaude"

mkdir -p /etc/pf.anchors
cp "$ANCHOR_SRC" "$ANCHOR_DST"
chmod 600 "$ANCHOR_DST"
/sbin/pfctl -n -a "$ANCHOR_NAME" -f "$ANCHOR_DST"
if ! grep -q "$MARK_BEGIN" "$PF_CONF" 2>/dev/null; then
  cp -p "$PF_CONF" "${PF_CONF}.peaceclaude.bak"
  printf '\n%%s\nanchor "%%s"\nload anchor "%%s" from "%%s"\n%%s\n' \
    "$MARK_BEGIN" "$ANCHOR_NAME" "$ANCHOR_NAME" "$ANCHOR_DST" "$MARK_END" >>"$PF_CONF"
  /sbin/pfctl -f "$PF_CONF" 2>/dev/null || true
fi
/sbin/pfctl -e 2>/dev/null || true
/sbin/pfctl -a "$ANCHOR_NAME" -f "$ANCHOR_DST"
echo "PeaceClaude pf anchor installed and active:"
/sbin/pfctl -a "$ANCHOR_NAME" -s rules
`, filepath.Join(config.PFDir(), "install-pf.sh"), anchorSrc)

	uninstallSh = fmt.Sprintf(`#!/usr/bin/env bash
set -euo pipefail
if [[ "$(id -u)" -ne 0 ]]; then
  echo "Please run with sudo: sudo bash %s" >&2
  exit 1
fi
ANCHOR_NAME="peaceclaude"
ANCHOR_DST="/etc/pf.anchors/peaceclaude"
PF_CONF="/etc/pf.conf"
/sbin/pfctl -a "$ANCHOR_NAME" -F rules 2>/dev/null || true
rm -f "$ANCHOR_DST"
if grep -q "# BEGIN peaceclaude" "$PF_CONF" 2>/dev/null; then
  python3 - <<'PY'
from pathlib import Path
p = Path("/etc/pf.conf")
t = p.read_text()
s = t.find("# BEGIN peaceclaude")
e = t.find("# END peaceclaude")
if s != -1 and e != -1:
    t = t[:s].rstrip() + "\n" + t[e + len("# END peaceclaude"):].lstrip()
    p.write_text(t)
PY
fi
echo "PeaceClaude pf anchor removed."
`, filepath.Join(config.PFDir(), "uninstall-pf.sh"))
	return installSh, uninstallSh
}

func WritePFArtifacts(cfg *config.Config) (anchorPath, installPath, uninstallPath string, err error) {
	if err := config.EnsureDirs(); err != nil {
		return "", "", "", err
	}
	dir := config.PFDir()
	anchorPath = filepath.Join(dir, "peaceclaude.pf.anchor")
	installPath = filepath.Join(dir, "install-pf.sh")
	uninstallPath = filepath.Join(dir, "uninstall-pf.sh")

	anchorText := RenderPFAnchor(cfg)
	if err := os.WriteFile(anchorPath, []byte(anchorText), 0o600); err != nil {
		return "", "", "", err
	}
	inst, uninst := RenderPFScripts(anchorPath)
	if err := os.WriteFile(installPath, []byte(inst), 0o700); err != nil {
		return "", "", "", err
	}
	if err := os.WriteFile(uninstallPath, []byte(uninst), 0o700); err != nil {
		return "", "", "", err
	}
	return anchorPath, installPath, uninstallPath, nil
}

func ValidatePFAnchorSyntax(anchorPath string) (bool, string) {
	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	defer cancel()
	out, err := exec.CommandContext(ctx, "/sbin/pfctl", "-n", "-f", anchorPath).CombinedOutput()
	msg := strings.TrimSpace(string(out))
	if err != nil {
		if msg == "" {
			msg = err.Error()
		}
		return false, msg
	}
	return true, "pfctl -n syntax valid"
}

func DetectCoworkBridge() (bool, string) {
	ifaces, err := net.Interfaces()
	if err != nil {
		return false, ""
	}
	for _, iface := range ifaces {
		if !strings.HasPrefix(iface.Name, "bridge") {
			continue
		}
		addrs, err := iface.Addrs()
		if err != nil {
			continue
		}
		for _, a := range addrs {
			ipNet, ok := a.(*net.IPNet)
			if !ok {
				continue
			}
			ip4 := ipNet.IP.To4()
			if ip4 != nil && strings.HasPrefix(ip4.String(), "192.168.64.") {
				return true, ip4.String()
			}
		}
	}
	return false, ""
}

func InspectVMProxy(cfg *config.Config) VMProxyStatus {
	anchorPath, installPath, uninstallPath, _ := WritePFArtifacts(cfg)
	valid, detail := ValidatePFAnchorSyntax(anchorPath)
	bridgeUp, bridgeIP := DetectCoworkBridge()

	_, errCage := os.Stat("/etc/pf.anchors/peaceclaude")
	_, errLegacy := os.Stat("/etc/pf.anchors/claude.egress")
	legacyDaemonMatches, _ := filepath.Glob("/Library/LaunchDaemons/*claude-killswitch*.plist")
	legacyDaemonInstalled := len(legacyDaemonMatches) > 0

	note := "未检测到系统级 pf killswitch，建议运行 sudo bash " + installPath
	if errCage == nil {
		note = "已安装 PeaceClaude pf killswitch (/etc/pf.anchors/peaceclaude)"
	} else if errLegacy == nil {
		note = "已检测到本机现有 pf killswitch (/etc/pf.anchors/claude.egress)，正在保护宿主机直连"
	}

	return VMProxyStatus{
		ConfigEnabled:         cfg != nil && cfg.Listen.VMProxyEnabled,
		PeacePFAnchorExists:    errCage == nil,
		LegacyPFAnchorExists:  errLegacy == nil,
		LegacyDaemonInstalled: legacyDaemonInstalled,
		CoworkBridgeActive:    bridgeUp,
		CoworkBridgeIP:        bridgeIP,
		RenderedAnchorPath:    anchorPath,
		InstallScriptPath:     installPath,
		UninstallScriptPath:   uninstallPath,
		SyntaxValid:           valid,
		SyntaxDetail:          detail,
		ActivePFNote:          note,
		Subnets:               cfg.Listen.VMProxySubnets,
	}
}

// InstallPFPrivileged invokes macOS native AppleScript administrator prompt to install and load
// the PeaceClaude pf killswitch anchor cleanly without requiring an external terminal.
func InstallPFPrivileged(ctx context.Context, cfg *config.Config) (string, error) {
	_, installPath, _, err := WritePFArtifacts(cfg)
	if err != nil {
		return "", err
	}
	if ctx == nil {
		ctx = context.Background()
	}
	cctx, cancel := context.WithTimeout(ctx, 45*time.Second)
	defer cancel()
	escapedPath := strings.ReplaceAll(installPath, `\`, `\\`)
	escapedPath = strings.ReplaceAll(escapedPath, `"`, `\"`)
	script := fmt.Sprintf(`do shell script "/bin/bash " & quoted form of "%s" with administrator privileges`, escapedPath)
	out, err := exec.CommandContext(cctx, "osascript", "-e", script).CombinedOutput()
	msg := strings.TrimSpace(string(out))
	if err != nil {
		if msg == "" {
			msg = err.Error()
		}
		return msg, fmt.Errorf("macOS 授权安装 pf 规则失败: %s", msg)
	}
	return msg, nil
}
